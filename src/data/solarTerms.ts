export function getSolarTermByIndex(index: number): SolarTermDetail | undefined {
  return SOLAR_TERMS.find((t) => t.index === index);
}

export function getSolarTermByLongitude(longitude: number): SolarTermDetail {
  const normalized = ((longitude % 360) + 360) % 360;
  const index = Math.round(normalized / 15) % 24;
  return SOLAR_TERMS[index];
}
